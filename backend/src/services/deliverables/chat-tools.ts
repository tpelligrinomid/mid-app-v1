/**
 * Deliverables in Ask Compass: read one in full, review it against what has
 * happened since, edit it in place, or revise it into a new deliverable.
 *
 * - Text deliverables (content_raw: content plans, research, briefs, most plans)
 *   are edited with exact find/replace (edit_deliverable).
 * - Structured-only deliverables (roadmaps, program roadmaps, points plans, SEO
 *   audits) are edited as data with JSON Pointer operations (edit_deliverable_data),
 *   limited to changes that keep the shape the app's renderers expect.
 * - Delivered deliverables are locked. revise_deliverable creates a new one,
 *   either regenerated by Master Marketer from the original plus a brief, or a
 *   copy that is then edited here; the original is kept as delivered.
 *
 * Each confirmed change bumps the minor version (1.0 -> 1.1) and stores the
 * full content of both the previous and the new version in
 * compass_deliverable_versions, so any version can be restored. Changes are
 * two-step: without confirm=true the tools only preview.
 *
 * Bound to one contract and one staff user; never offered to client users.
 */
