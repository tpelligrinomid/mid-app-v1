/** System-prompt section for the deliverable the user has open in the app. */
export function openDeliverablePrompt(d: DeliverableRow, canEdit: boolean, beingEdited = false): string {
  const text = deliverableText(d);
  const truncated = text.length > MAX_DELIVERABLE_CHARS;
  const kind = editKind(d);
  const meta = [
    d.deliverable_type,
    `version ${d.version || '1.0'}`,
    d.status,
    d.created_at && `created ${d.created_at.slice(0, 10)}`,
    d.updated_at && `last updated ${d.updated_at.slice(0, 10)}`,
  ]
    .filter(Boolean)
    .join(', ');

  let editNote = '';
  if (canEdit) {
    if (beingEdited) {
      editNote = `\n\nThe user has this deliverable open in the app's editor right now, so don't change it from here: their Save would overwrite it. You can still review it and draft changes; to apply them, ask them to save or cancel their edits first.`;
    } else if (d.status === 'delivered') {
      editNote = `\n\nThis deliverable is **Delivered**, so it is locked: don't propose in-place edits. If the user wants changes, offer revise_deliverable, which creates a new deliverable and keeps this one as delivered: mode 'regenerate'${REGENERATE_TYPES.has(d.deliverable_type ?? '') ? '' : ' is not available for this type, so use'} ${REGENERATE_TYPES.has(d.deliverable_type ?? '') ? "for a rethink, or 'copy' for targeted changes (then edit the copy)" : "'copy' and then edit the copy"}. A strategist can also set it back to Working to edit it in place.`;
    } else if (kind === 'text') {
      editNote = `\n\nTo change it, use edit_deliverable (deliverable_id ${d.deliverable_id}) with passages copied exactly from the text below. Keep edits surgical and keep the document's structure, headings and formatting. Preview first; confirm only after the user agrees. Say which version the change creates. If the changes amount to a pivot rather than adjustments, offer revise_deliverable instead, so the current version is preserved.`;
    } else if (kind === 'data') {
      editNote = `\n\nThis deliverable is structured data (shown below as JSON). To change it, use edit_deliverable_data (deliverable_id ${d.deliverable_id}) with JSON Pointer paths into this JSON; keep its shape and keep totals consistent. Describe changes to the user in plain language (sections, months, tasks), not paths. Preview first; confirm only after the user agrees. If the changes amount to a pivot, offer revise_deliverable instead.`;
    }
  }

  return `## Open deliverable

The user has this deliverable open in the app and is asking about it: "${d.title}" (${meta}), deliverable_id ${d.deliverable_id}. Its full ${kind === 'data' ? 'data' : 'text'} is below. Answer questions about it from this, and say when something isn't in it.

To review progress against it, compare what it commits to (topics and clusters, cadence, keywords, channels, KPIs, budgets, dates, owners) with what has actually happened since ${d.created_at?.slice(0, 10) ?? 'it was created'}: content published (find_content_references with kinds ["asset"]), rankings for its keywords (SEO tools), performance (marketing data tools) and recent meetings and notes. Be concrete: list planned vs done with dates, call out gaps and what's ahead of plan, then suggest adjustments.${editNote}

<deliverable title="${d.title.replace(/"/g, "'")}">
${truncated ? `${text.slice(0, MAX_DELIVERABLE_CHARS)}\n[... truncated: the deliverable continues beyond this point]` : text}
</deliverable>`;
}

