/** 1.0 -> 1.1, 2.9 -> 2.10, "3" -> 3.1. */
function nextMinorVersion(version: string | null): string {
  const [major, minor] = (version || '1.0').split('.');
  const maj = Number.parseInt(major, 10);
  const min = Number.parseInt(minor ?? '0', 10);
  return `${Number.isFinite(maj) ? maj : 1}.${(Number.isFinite(min) ? min : 0) + 1}`;
}

function countOccurrences(haystack: string, needle: string): number {
  if (!needle) return 0;
  let count = 0;
  for (let i = haystack.indexOf(needle); i !== -1; i = haystack.indexOf(needle, i + needle.length)) count++;
  return count;
}

function clip(text: string, max = 600): string {
  return text.length > max ? `${text.slice(0, max)}…` : text;
}

/** JSON with object keys sorted (the database reorders jsonb keys, so compare canonically). */
function canonical(v: unknown): string {
  if (Array.isArray(v)) return `[${v.map(canonical).join(',')}]`;
  if (v && typeof v === 'object') {
    return `{${Object.keys(v as object).sort().map((k) => `${JSON.stringify(k)}:${canonical((v as Record<string, unknown>)[k])}`).join(',')}}`;
  }
  return JSON.stringify(v);
}

function clipJson(value: unknown, max = 600): string {
  return value === undefined ? '(none)' : clip(JSON.stringify(value), max);
}

/** The deliverable's readable text: the markdown when there is one, else its structured data. */
export function deliverableText(d: Pick<DeliverableRow, 'content_raw' | 'content_structured'>): string {
  if (d.content_raw) return d.content_raw;
  if (d.content_structured) return JSON.stringify(d.content_structured, null, 1);
  return '';
}

/** Text deliverables are edited as text; structured-only ones as data. */
function editKind(d: Pick<DeliverableRow, 'content_raw' | 'content_structured'>): 'text' | 'data' | null {
  if (d.content_raw) return 'text';
  if (d.content_structured) return 'data';
  return null;
}

// ── JSON Pointer operations ────────────────────────────────────────────

type Json = unknown;

function parsePointer(path: string): string[] | null {
  if (path === '') return [];
  if (!path.startsWith('/')) return null;
  return path
    .slice(1)
    .split('/')
    .map((s) => s.replace(/~1/g, '/').replace(/~0/g, '~'));
}

function kindOf(v: Json): string {
  if (v === null) return 'null';
  if (Array.isArray(v)) return 'list';
  return typeof v === 'object' ? 'object' : typeof v;
}

/** Shape check: same kind; objects keep every existing field. Null on either side is allowed. */
function shapeProblem(oldValue: Json, newValue: Json): string | null {
  if (oldValue === null || oldValue === undefined || newValue === null) return null;
  const ok = kindOf(oldValue);
  const nk = kindOf(newValue);
  if (ok !== nk) return `expected ${ok}, got ${nk}`;
  if (ok === 'object') {
    const missing = Object.keys(oldValue as object).filter((k) => !(k in (newValue as object)));
    if (missing.length > 0) return `object is missing fields: ${missing.join(', ')}`;
  }
  return null;
}

/** Applies one operation to `doc` in place; returns a description or a problem. */
function applyOperation(
  doc: Json,
  op: { op?: unknown; path?: unknown; value?: unknown }
): { ok: true; before: Json; after: Json } | { ok: false; problem: string } {
  const segments = typeof op.path === 'string' ? parsePointer(op.path) : null;
  if (!segments || segments.length === 0) return { ok: false, problem: 'path must be a JSON Pointer like /section/0/field' };
  const key = segments[segments.length - 1];
  let parent: Json = doc;
  for (const seg of segments.slice(0, -1)) {
    if (Array.isArray(parent)) parent = parent[Number(seg)];
    else if (parent && typeof parent === 'object') parent = (parent as Record<string, Json>)[seg];
    else parent = undefined;
    if (parent === undefined) return { ok: false, problem: `path not found at "${seg}"` };
  }
  if (!parent || typeof parent !== 'object') return { ok: false, problem: 'path does not lead into a list or object' };

  if (op.op === 'insert') {
    if (!Array.isArray(parent)) return { ok: false, problem: 'insert needs a list path ending in an index or "-"' };
    const index = key === '-' ? parent.length : Number(key);
    if (!Number.isInteger(index) || index < 0 || index > parent.length) return { ok: false, problem: `index ${key} is outside the list (0-${parent.length})` };
    if (op.value === undefined) return { ok: false, problem: 'insert needs a value' };
    if (parent.length > 0) {
      const problem = shapeProblem(parent[0], op.value);
      if (problem) return { ok: false, problem: `new item doesn't match its siblings: ${problem}` };
    }
    parent.splice(index, 0, op.value);
    return { ok: true, before: undefined, after: op.value };
  }

  const exists = Array.isArray(parent) ? Number.isInteger(Number(key)) && Number(key) >= 0 && Number(key) < parent.length : key in (parent as object);
  if (!exists) return { ok: false, problem: 'path not found' };
  const before = Array.isArray(parent) ? parent[Number(key)] : (parent as Record<string, Json>)[key];

  if (op.op === 'remove') {
    if (Array.isArray(parent)) parent.splice(Number(key), 1);
    else delete (parent as Record<string, Json>)[key];
    return { ok: true, before, after: undefined };
  }
  if (op.op === 'set') {
    if (op.value === undefined) return { ok: false, problem: 'set needs a value' };
    const problem = shapeProblem(before, op.value);
    if (problem) return { ok: false, problem };
    if (Array.isArray(parent)) parent[Number(key)] = op.value;
    else (parent as Record<string, Json>)[key] = op.value;
    return { ok: true, before, after: op.value };
  }
  return { ok: false, problem: `unknown op "${String(op.op)}"` };
}

